def test_hdfc_icici_axis_extractors():
    hdfc_lines = [
        "HDFC Bank Statement",
        "07/06/2026  UPI BIGBASKET HDFC123456  275.00  0.00  11226.00",
    ]
    icici_lines = [
        "ICICI Bank Statement",
        "08/06/2026  UPI MYNTRA ICICI654321  999.00  0.00  10227.00",
    ]
    axis_lines = [
        "Axis Bank Statement",
        "09/06/2026  UPI IRCTC AXIS999888  1499.00  0.00  8728.00",
    ]

    assert _extract_hdfc_transactions(hdfc_lines, "\n".join(hdfc_lines))[0]["amount"] == 275.0
    assert _extract_icici_transactions(icici_lines, "\n".join(icici_lines))[0]["amount"] == 999.0
    assert _extract_axis_transactions(axis_lines, "\n".join(axis_lines))[0]["amount"] == 1499.0
