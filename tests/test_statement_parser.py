def test_detect_supported_providers():
    assert _detect_pdf_provider("PhonePe transaction statement") == "phonepe"
    assert _detect_pdf_provider("Google Pay transaction history") == "google_pay"
    assert _detect_pdf_provider("Paytm Payments Bank account statement") == "paytm"
    assert _detect_pdf_provider("BHIM UPI statement generated by NPCI") == "bhim"
    assert _detect_pdf_provider("State Bank of India account statement") == "sbi"
    assert _detect_pdf_provider("Bank of Baroda statement") == "bank_of_baroda"
    assert _detect_pdf_provider("HDFC Bank account statement") == "hdfc"
    assert _detect_pdf_provider("ICICI Bank statement") == "icici"
    assert _detect_pdf_provider("Axis Bank statement") == "axis"


def test_phonepe_extractor():
    lines = [
        "PhonePe Transaction Statement",
        "01 Jun 2026",
        "09:12 AM",
        "Paid to Swiggy",
        "swiggy@ibl",
        "PhonePe Transaction ID: PP123456789",
        "UTR: 123456789012",
        "INR 420.00",
        "SUCCESS",
    ]

    transactions = _extract_phonepe_transactions(lines, "\n".join(lines))

    assert len(transactions) == 1
    assert transactions[0]["amount"] == 420.0
    assert transactions[0]["merchant"] == "Swiggy"


