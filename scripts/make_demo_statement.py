"""Build a SYNTHETIC UPI statement for demonstrating the risk engine.

Why this exists
---------------
Showing the system working needs a statement with fraud in it. A real one
cannot be used: it carries a real phone number, a real card tail and the
names of real people who never agreed to appear in a project demo. So this
generates one instead, and the output says on every page that it is generated
test data rather than a record of any account.

What it produces
----------------
    docs/demo/DEMO_UPI_Statement.pdf   in the wallet-statement layout the
                                       parser reads, ~3 months of traffic
    docs/demo/DEMO_UPI_Statement.csv   the same rows, for any path that takes
                                       a CSV instead
    docs/demo/DEMO_ANSWER_KEY.md       which rows are planted, and which check
                                       is meant to fire on each

The legitimate traffic is not filler. It is what makes the planted rows
detectable at all: the engine scores a payment against the payer's OWN
history, so a demo statement with no established habits gives every feature
nothing to compare against. That is why this builds ~3 months of canteen
payments, a monthly rent, repeat friends and an autopay before it plants
anything.

    python scripts/make_demo_statement.py
"""

