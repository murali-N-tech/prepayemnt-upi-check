# A fictional account. Not a real number, not a real card.
ACCOUNT = "9000000000"
CARD_TAIL = "XXXXXX4242"
# The period ends today and runs back 92 days. This matters: the reputation
# store measures a payee's age against the clock at the moment of the check,
# so a statement pinned to fixed dates would show a "four-day-old" address as
# four months old by the time anyone demonstrates it. Regenerate the file and
# the dates move with you.
TODAY = datetime.now().replace(hour=21, minute=0, second=0, microsecond=0)
END = TODAY
START = (TODAY - timedelta(days=92)).replace(hour=0, minute=0)
SEED = 2026

BANNER = "SYNTHETIC DEMO DATA - GENERATED BY scripts/make_demo_statement.py - NOT A REAL ACCOUNT"

# DejaVu carries the rupee sign and the Cyrillic block. Both matter: the
# amounts need the first, and the planted lookalike payee needs the second.
FONT_DIR = Path("/usr/share/fonts/truetype/dejavu")
FONTS = {
    "Demo": FONT_DIR / "DejaVuSans.ttf",
    "Demo-Bold": FONT_DIR / "DejaVuSans-Bold.ttf",
}


@dataclass
class Tx:
    when: datetime
    counterparty: str
    vpa: str
    amount: float
    direction: str                  # DEBIT | CREDIT
    autopay: bool = False
    planted: str = ""               # empty for legitimate traffic
    tags: list[str] = field(default_factory=list)


def _ref(rng: random.Random, prefix: str, n: int) -> str:
    return prefix + "".join(str(rng.randint(0, 9)) for _ in range(n))


# ── The payer's ordinary life ────────────────────────────────────────────────
# Every payee here is invented. The point of the mix is to give the engine a
# baseline with real shape: a few payees paid constantly (high pair count,
# high repeat ratio), a genuine large recurring payment so that "large" alone
# is not suspicious, and credits so the account is not one-directional.

def legitimate(rng: random.Random) -> list[Tx]:
    """Three months of ordinary traffic for a salaried adult.

    The spending level is chosen, not incidental. The model was trained on a
    population whose median payment is around ₹270, and the amount feature it
    reads is the payment divided by the payer's OWN median. A persona whose
    median is ₹25 - all ten-rupee autopays and twenty-rupee tea - pushes every
    ratio an order of magnitude outside the range the model ever saw, and the
    scores come back flat. So this persona buys groceries, takes cabs and pays
    rent, and lands near ₹300.
    """
    rows: list[Tx] = []
    day = START

    def at(d: datetime, h: int, m_lo: int, m_hi: int) -> datetime:
        return d.replace(hour=h, minute=rng.randint(m_lo, m_hi), second=0, microsecond=0)

    while day <= END:
        weekday = day.weekday()

        # Office cafeteria, most working days.
        if weekday < 5 and rng.random() < 0.85:
            rows.append(Tx(at(day, rng.choice([9, 13, 13, 16]), 0, 59), "SRI LAKSHMI CANTEEN",
                           "srilakshmi.canteen@ybl",
                           rng.choice([45, 60, 75, 90, 110, 120, 140]), "DEBIT"))

        # Groceries and the neighbourhood store.
        if rng.random() < 0.55:
            name, vpa = rng.choice([
                ("FRESHMART SUPERSTORE", "freshmart.store@ibl"),
                ("SRI VENKATESWARA KIRANA", "svkirana@paytm"),
            ])
            rows.append(Tx(at(day, rng.choice([18, 19, 20]), 0, 59), name, vpa,
                           round(rng.uniform(160, 940), 2), "DEBIT"))

        # Cabs and autos.
        if rng.random() < 0.62:
            rows.append(Tx(at(day, rng.choice([8, 9, 18, 19, 21]), 0, 59), "METRO RIDE MOBILITY",
                           "metroride.trips@ibl", round(rng.uniform(58, 265), 2), "DEBIT"))

        # Food delivery a few evenings a week.
        if rng.random() < 0.36:
            rows.append(Tx(at(day, 20, 0, 59), "QUICKBITE FOODS PRIVATE LIMITED",
                           "quickbite.foods@ibl", round(rng.uniform(149, 465), 2), "DEBIT"))

        # Chemist / medical store, occasionally.
        if rng.random() < 0.1:
            rows.append(Tx(at(day, rng.randint(10, 20), 0, 59), "SAI MEDICALS",
                           "saimedicals@ybl", round(rng.uniform(85, 620), 2), "DEBIT"))

        # Friends and family, both directions. These build the repeat-payer
        # shape that separates a real counterparty from a one-shot one.
        if rng.random() < 0.38:
            name, vpa = rng.choice([
                ("RAVI TEJA K", "raviteja.k@oksbi"),
                ("SNEHA P", "sneha.p@ybl"),
                ("ARJUN M", "arjun.m@paytm"),
                ("DEEPTHI R", "deepthi.r@axl"),
            ])
            out = rng.random() < 0.55
            rows.append(Tx(at(day, rng.randint(11, 21), 0, 59), name, vpa,
                           rng.choice([100, 150, 200, 250, 300, 500, 800, 1200]),
                           "DEBIT" if out else "CREDIT"))

        # Fuel, roughly weekly.
        if weekday == 5 and rng.random() < 0.75:
            rows.append(Tx(at(day, 17, 0, 50), "METROFUEL PUMP 42",
                           "metrofuel42@ibl", round(rng.uniform(600, 1450), 2), "DEBIT"))

        # Rail tickets now and then.
        if rng.random() < 0.06:
            rows.append(Tx(at(day, rng.randint(9, 22), 0, 59), "IRCTC TICKETING",
                           "irctc.tickets@sbi", round(rng.uniform(240, 860), 2), "DEBIT"))

        # ── Monthly anchors ──────────────────────────────────────────────
        # Rent. This is the row that stops "large amount" from being a proxy
        # for fraud: the payer genuinely sends five figures every month, so
        # F3 has to be caught on who is paid and when, not merely on size.
        if day.day == 3:
            rows.append(Tx(at(day, 10, 0, 40), "K RAMANA RAO",
                           "ramanarao.k@oksbi", 18500, "DEBIT"))
        if day.day == 5:
            rows.append(Tx(at(day, 19, 0, 50), "AXIS POWER UTILITY",
                           "axispower.utility@axl", round(rng.uniform(980, 2240), 2), "DEBIT"))
        if day.day == 7:
            rows.append(Tx(at(day, rng.choice([7, 8, 9]), 0, 59), "CLOUDNOTE SUBSCRIPTION",
                           "cloudnote.sub@ybl", 199, "DEBIT", autopay=True))
        if day.day == 9:
            rows.append(Tx(at(day, rng.choice([7, 8]), 0, 59), "SIP AUTOSAVE PLAN",
                           "sipautosave@ybl", 2500, "DEBIT", autopay=True))
        if day.day == 12:
            rows.append(Tx(at(day, rng.randint(10, 19), 0, 59), "BROADBAND FIBRENET",
                           "fibrenet.billing@axl", 799, "DEBIT"))
        if day.day == 1:
            rows.append(Tx(at(day, 11, 0, 30), "VERTEX SOFTWARE SOLUTIONS",
                           "vertexsoft.payroll@icici", 48000, "CREDIT"))

        day += timedelta(days=1)

    return rows


# ── The planted rows ─────────────────────────────────────────────────────────
# One block per attack the report describes, so a judge can be shown the
# mechanism rather than a single undifferentiated "fraud" flag.

def planted() -> list[Tx]:
    """The compromise. Three months of ordinary traffic, then a bad week.

    Every event is placed relative to today rather than on a fixed date, so
    that when the reputation store is asked how old one of these addresses is
    it answers in days, not months. Clustering them at the end is also what
    the real thing looks like: an account is fine until it is not.
    """
    rows: list[Tx] = []

    def d(days_ago: int, hh: int, mm: int) -> datetime:
        return (TODAY - timedelta(days=days_ago)).replace(hour=hh, minute=mm, second=0,
                                                          microsecond=0)

    # F1 - probe burst. A tested credential: a run of tiny payments to
    # addresses never paid before, inside half an hour, at 2am. Caught on
    # velocity, hour familiarity and an all-new payee set.
    for i in range(8):
        rows.append(Tx(d(6, 2, 14) + timedelta(minutes=3 * i),
                       f"VERIFY0{i + 1} SERVICES", f"verify0{i + 1}@quickpay",
                       [1, 2, 5, 9, 14, 21, 33, 47][i], "DEBIT",
                       planted="F1", tags=["velocity", "night", "all payees new"]))

    # F2 - funnel account. One address opened days earlier taking a rapid
    # series of one-shot payments and returning nothing. Caught entirely from
    # the payee side: the payer behaves normally throughout.
    for i in range(5):
        rows.append(Tx(d(4, 18, 2) + timedelta(minutes=11 * i),
                       "QUICKCASH AGENCY", "quickcash.agency@fastpay", 4500, "DEBIT",
                       planted="F2", tags=["payee 3 days old", "no repeat payers", "burst"]))

    # F3 - hijacked profile. Someone else is operating the account: three
    # payments in eleven minutes, each far above anything this payer sends, at
    # an hour they have never used, to addresses they have never paid.
    #
    # This was one lone payment at first, and it was the wrong shape. A
    # takeover empties an account while the access lasts; it does not send one
    # transfer and go to bed. The single-row version only scored because the
    # payee had two payers and a repeat ratio of 0.0 - an empty sample that
    # happens to look identical to a collection account - so the demo was
    # leaning on a number that should never have been decisive, and it fell
    # over the moment thin samples stopped being trusted. Velocity is what
    # actually identifies this scenario, and now the rows carry it.
    for i, (mins, amount, payee, vpa) in enumerate([
        (0, 49500, "NEHRU TRADERS ENTERPRISE", "nehru.traders99@fastpay"),
        (5, 92400, "NEHRU TRADERS ENTERPRISE", "nehru.traders99@fastpay"),
        (11, 38750, "RK GENERAL SUPPLIES", "rk.supplies77@fastpay"),
    ]):
        rows.append(Tx(d(3, 3, 47) + timedelta(minutes=mins), payee, vpa, amount, "DEBIT",
                       planted="F3", tags=["amount vs own median", "night",
                                           "three transfers in eleven minutes"]))

    # F4 - victim-authorised transfer. The class the behavioural model is
    # weakest on, and the reason the other channels exist. Ordinary hour,
    # amount within reach of this payer's rent, new payee. The 1 rupee credit
    # thirteen minutes earlier is the refund-scam opening: a token payment to
    # prove the "refund" works before the real ask.
    rows.append(Tx(d(2, 11, 19), "ELECTRICITY BILL DESK", "electricity.billdesk@upiservice",
                   1, "CREDIT", planted="F4", tags=["token credit", "refund-scam opening"]))
    rows.append(Tx(d(2, 11, 32), "ELECTRICITY BILL DESK", "electricity.billdesk@upiservice",
                   18000, "DEBIT",
                   planted="F4", tags=["new payee", "no behavioural anomaly at all"]))

    # F5 - lookalike address. The handle is @yb1, digit one, against the real
    # @ybl, letter ell. In the sans-serif face every payment app renders a VPA
    # in, those two glyphs are all but identical. The local part then pairs a
    # bank's name with the word "refund", which no bank handle ever does.
    #
    # A Cyrillic homoglyph was tried here first and is the wrong choice for a
    # demo: the character fails the UPI ID validity check before the brand
    # comparison runs, so it reports as malformed - correct, and blocking, but
    # it does not show the machinery. This address scores 100 on two separate
    # critical findings and names the bank it is imitating.
    rows.append(Tx(d(1, 19, 21), "HDFC BANK REFUND CELL", "hdfcbank.refund@yb1",
                   47500, "DEBIT",
                   planted="F5", tags=["confusable handle @yb1 vs @ybl",
                                       "bank name paired with 'refund'"]))

    return rows


