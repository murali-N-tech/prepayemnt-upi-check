def write_seed(path: Path) -> None:
    payload = {
        "note": ("Counterparty crowd for docs/demo/DEMO_UPI_Statement.pdf. "
                 "Ages are in days before the moment of loading, so the file "
                 "does not go stale. Load with: python "
                 "scripts/bootstrap_payee_reputation.py --demo-statement"),
        "payees": [
            {"vpa": v, "display_name": n, "age_days": a,
             "other_payers": p, "payments_each": e, "typical_amount": amt}
            for v, n, a, p, e, amt in PAYEE_CROWD
        ],
    }
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")


# ── Rendering ────────────────────────────────────────────────────────────────

def render_pdf(rows: list[Tx], path: Path, rng: random.Random) -> int:
    for name, file in FONTS.items():
        pdfmetrics.registerFont(TTFont(name, str(file)))

    W, H = A4
    c = canvas.Canvas(str(path), pagesize=A4)
    left, right = 18 * mm, W - 18 * mm
    pages = 0

    def banner():
        c.setFillColorRGB(0.75, 0.15, 0.15)
        c.setFont("Demo-Bold", 7)
        c.drawCentredString(W / 2, H - 10 * mm, BANNER)
        c.setFillColorRGB(0, 0, 0)

    def header(first: bool) -> float:
        nonlocal pages
        pages += 1
        banner()
        y = H - 22 * mm
        if first:
            c.setFont("Demo-Bold", 14)
            c.drawString(left, y, f"Transaction Statement for {ACCOUNT}")
            y -= 6 * mm
            c.setFont("Demo", 9.5)
            c.drawString(left, y, f"{START:%d %b, %Y} - {END:%d %b, %Y}")
            y -= 4 * mm
            c.setFont("Demo", 8)
            c.drawString(left, y, "PhonePe statement layout (synthetic sample for testing a parser)")
            y -= 8 * mm
        c.setFillColorRGB(0.96, 0.96, 0.97)
        c.rect(left, y - 2 * mm, right - left, 7 * mm, fill=1, stroke=0)
        c.setFillColorRGB(0.35, 0.35, 0.40)
        c.setFont("Demo-Bold", 9)
        c.drawString(left + 2 * mm, y, "Date")
        c.drawString(left + 34 * mm, y, "Transaction Details")
        c.drawString(right - 44 * mm, y, "Type")
        c.drawRightString(right - 2 * mm, y, "Amount")
        c.setFillColorRGB(0, 0, 0)
        return y - 9 * mm

    def footer():
        c.setFont("Demo", 7.5)
        c.setFillColorRGB(0.45, 0.45, 0.45)
        c.drawCentredString(W / 2, 14 * mm, f"Page {pages}")
        c.drawCentredString(W / 2, 10 * mm,
                            "Generated test data. No real account, card or person is represented.")
        c.setFillColorRGB(0, 0, 0)

    y = header(first=True)
    for tx in rows:
        if y < 34 * mm:
            footer()
            c.showPage()
            y = header(first=False)

        credit = tx.direction == "CREDIT"
        verb = "Received from" if credit else "Paid to"

        c.setFont("Demo", 8.5)
        c.setFillColorRGB(0.25, 0.25, 0.30)
        c.drawString(left + 2 * mm, y, f"{tx.when:%b %d, %Y}")
        c.drawString(left + 2 * mm, y - 4.2 * mm, f"{tx.when:%I:%M %p}")
        c.setFillColorRGB(0, 0, 0)

        c.setFont("Demo-Bold", 9)
        c.drawString(left + 34 * mm, y, f"{verb} {tx.counterparty}")
        c.setFont("Demo", 7.8)
        c.setFillColorRGB(0.42, 0.42, 0.47)
        c.drawString(left + 34 * mm, y - 4.2 * mm, f"UPI ID: {tx.vpa}")
        c.drawString(left + 34 * mm, y - 8.0 * mm,
                     f"Transaction ID T{tx.when:%y%m%d}{_ref(rng, '', 14)}")
        c.drawString(left + 34 * mm, y - 11.8 * mm, f"UTR No. {_ref(rng, '', 12)}")
        tail = f"{'Credited to' if credit else 'Paid by'}  {CARD_TAIL}"
        if tx.autopay:
            tail += "   AUTOPAY"
        c.drawString(left + 34 * mm, y - 15.6 * mm, tail)
        c.setFillColorRGB(0, 0, 0)

        c.setFont("Demo-Bold", 8.5)
        if credit:
            c.setFillColorRGB(0.05, 0.55, 0.30)
        c.drawString(right - 44 * mm, y, tx.direction)
        c.setFont("Demo-Bold", 9.5)
        c.drawRightString(right - 2 * mm, y, f"₹{tx.amount:,.2f}".rstrip("0").rstrip("."))
        c.setFillColorRGB(0, 0, 0)

        c.setStrokeColorRGB(0.90, 0.90, 0.92)
        c.line(left, y - 19 * mm, right, y - 19 * mm)
        y -= 23 * mm

    footer()
    c.save()
    return pages


def write_csv(rows: list[Tx], path: Path) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["timestamp", "counterparty", "upi_id", "amount", "direction",
                    "planted_scenario", "expected_signal"])
        for tx in rows:
            w.writerow([tx.when.strftime("%Y-%m-%d %H:%M:%S"), tx.counterparty, tx.vpa,
                        f"{tx.amount:.2f}", tx.direction, tx.planted, "; ".join(tx.tags)])


